export const getAllUsers = () => [...admins, ...doctors, ...patients];

export const getUserById = (id: string) => getAllUsers().find(u => u.id === id);

export const getUserByEmail = (email: string) => getAllUsers().find(u => u.email === email);

export const getPatientById = (id: string) => patients.find(p => p.id === id);

export const getDoctorById = (id: string) => doctors.find(d => d.id === id);

export const getRecordsByPatientId = (patientId: string) => 
  medicalRecords.filter(r => r.pacienteId === patientId);

export const getRecordsByDoctorId = (doctorId: string) => 
  medicalRecords.filter(r => r.medicoId === doctorId);

export const getPatientsByDoctorId = (doctorId: string) => {
  const doctor = getDoctorById(doctorId);
  if (!doctor) return [];
  return patients.filter(p => doctor.pacientes.includes(p.id));
};

export const getDashboardStats = () => {
  const activeRecords = medicalRecords.filter(r => r.status !== 'RESOLVIDO');
  const criticalRecords = medicalRecords.filter(r => r.severidade === 'CRITICA' || r.severidade === 'ALTA');
  const resolvedRecords = medicalRecords.filter(r => r.status === 'RESOLVIDO');
  
  return {
    totalPacientes: patients.length,
    totalMedicos: doctors.length,
    totalRegistros: medicalRecords.length,
    registrosAtivos: activeRecords.length,
    registrosCriticos: criticalRecords.length,
    registrosResolvidos: resolvedRecords.length,
  };
};
